// Icon props shared by every icon in the registry
export interface IconProps {
  size?: number | string;
  color?: string;
  fill?: string;
  stroke?: string;
  strokeWidth?: number | string;
  className?: string;
  style?: CSSProperties;
  weight?: "thin" | "light" | "regular" | "bold" | "fill" | "duotone";
}

export type Icon = ComponentType<IconProps>;

/** A Hugeicons glyph as a component taking the app's icon props. */
function huge(glyph: IconSvgElement): Icon {
  // `weight` and `fill` belonged to the previous icon sets and have no meaning
  // here; everything else (aria-label, title, handlers) reaches the <svg>.
  return function HugeIcon({ size, color, strokeWidth, weight: _weight, fill: _fill, ...rest }: IconProps) {
    return (
      <HugeiconsIcon
        icon={glyph}
        size={size ?? 24}
        color={color ?? "currentColor"}
        strokeWidth={Number(strokeWidth ?? 1.5)}
        {...rest}
      />
    );
  };
}

